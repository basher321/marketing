/**
 * Conversation AI-reply-draft types (SPEC-FE-014), mirroring the backend
 * Pydantic schemas in app/schemas/conversation.py field for field.
 *
 * The conversations-list types (InboxItem / InboxList) are SPEC-FE-013's,
 * mirroring backend InboxItem / InboxList (SPEC-BE-007).
 */

/**
 * Derived inbox status (backend SPEC-BE-007 rule 4). escalated / draft_ready /
 * auto_replied are the mockup's three badges; new and replied are the two real
 * states the mockup has no badge for (neutral badge, decided in SPEC-BE-007).
 */
export type InboxStatus = "escalated" | "draft_ready" | "new" | "auto_replied" | "replied";

/** One row of the Open Conversations table — backend InboxItem. */
export interface InboxItem {
  id: string;
  /** "First Last", else email, else phone; null when unknown. */
  customer_name: string | null;
  /** Live channel_type value, e.g. "instagram". */
  channel: string;
  topic: string | null;
  /** ISO 8601 UTC time of the customer's latest message; null if they never wrote. */
  waiting_since: string | null;
  inbox_status: InboxStatus;
  /** Raw conversation_status: "open" | "pending". */
  status: string;
}

/** GET /api/v1/conversations — backend InboxList; count === items.length. */
export interface InboxList {
  count: number;
  items: InboxItem[];
}

/**
 * One grounding source exactly as SPEC-BE-027 returned it — backend
 * GroundingSourceRead (see app/ai/retrieval.py GroundingSource).
 */
export interface GroundingSource {
  /** "kb_document" | "faq" */
  kind: string;
  id: string;
  title: string;
  snippet: string;
  score: number;
}

/** backend DraftRead: the conversation's pending (unsent) AI reply draft. */
export interface DraftRead {
  id: string;
  /** Plain text; carries no emphasis markers. */
  body: string;
  /** ISO 8601 datetime (UTC). */
  created_at: string;
  /**
   * 0–1 scale, computed deterministically server-side (0.20–0.95 for
   * generated drafts). null on drafts not generated by SPEC-BE-027 (e.g.
   * seeded rows).
   */
  confidence: number | null;
  /** [] on non-generated drafts and on the no-grounding fallback. */
  sources: GroundingSource[];
}

/**
 * GET/PATCH /api/v1/conversations/{id}/draft and POST .../draft/generate —
 * backend DraftResponse. draft is null when there is no pending draft (the
 * documented empty response, not an error).
 */
export interface DraftResponse {
  draft: DraftRead | null;
}

/** PATCH /api/v1/conversations/{id}/draft body — backend DraftEdit (trimmed, 1–8000 chars). */
export interface DraftEdit {
  body: string;
}

/**
 * POST /api/v1/conversations/{id}/draft/send — backend DraftSendResult. The
 * endpoint takes no body: it sends the stored draft as-is.
 */
export interface DraftSendResult {
  message_id: string;
  body: string;
  /** ISO 8601 datetime (UTC). */
  sent_at: string;
}

/**
 * POST /api/v1/conversations/{id}/handoff — backend HandoffResult. The backend
 * records an audit_log row and (SPEC-BE-007) a metadata marker that makes the
 * inbox show "Escalated"; conversations.status is not changed and the draft
 * stays pending.
 */
export interface HandoffResult {
  conversation_id: string;
  /** ISO 8601 datetime (UTC). */
  handed_off_at: string;
}
