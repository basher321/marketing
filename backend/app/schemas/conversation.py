"""Conversation and message schemas."""
from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, BeforeValidator, ConfigDict, StringConstraints


class MessageCreate(BaseModel):
    sender_type: str = "customer"
    body: str


class MessageRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    sender_type: str
    body: str


# Live uuid columns come back as uuid.UUID; coerce to str for the API
# (SPEC-BE-028, needed for the list route to serialize).
UUIDStr = Annotated[str, BeforeValidator(lambda v: str(v) if v is not None else v)]


# Derived inbox status (SPEC-BE-007 rule 4). The mockup's badges are escalated
# ("Escalated"), draft_ready ("Draft ready") and auto_replied ("Auto-replied");
# new and replied are the two real states the mockup has no badge for.
InboxStatus = Literal["escalated", "draft_ready", "new", "auto_replied", "replied"]


class InboxItem(BaseModel):
    """One row of the Customer Service page's Open Conversations table."""

    id: str
    customer_name: str | None
    channel: str
    topic: str | None
    # UTC time of the customer's latest message; the frontend renders "2m"/"1h".
    waiting_since: datetime | None
    inbox_status: InboxStatus
    # Raw live conversation_status: open or pending (the only ones listed).
    status: str


class InboxList(BaseModel):
    # Always len(items): the "Open Conversations (N)" heading.
    count: int
    items: list[InboxItem]


class CsMetrics(BaseModel):
    """Dashboard Customer Service engine card: Avg. response, Deflection rate,
    CSAT (7d) (SPEC-BE-021). null = no data / placeholder, never a guess."""

    avg_response_seconds: float | None
    deflection_rate_pct: float | None
    csat_7d: float | None


class DraftEdit(BaseModel):
    """New text for the pending AI reply draft (SPEC-BE-026); whitespace is
    stripped first, so an empty edit fails with 422 before any write."""

    body: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=8000)]


class GroundingSourceRead(BaseModel):
    """One grounding source exactly as SPEC-BE-027 returned it (SPEC-BE-028)."""

    kind: str
    id: str
    title: str
    snippet: str
    score: float


class DraftRead(BaseModel):
    id: str
    body: str
    created_at: datetime
    # SPEC-BE-028: set on generated drafts; null / [] on drafts that were not
    # generated by SPEC-BE-027 (e.g. seeded rows).
    confidence: float | None = None
    sources: list[GroundingSourceRead] = []


class DraftResponse(BaseModel):
    """Get-draft result: draft is null when the conversation has no pending
    draft (the documented empty response, not an error)."""

    draft: DraftRead | None


class DraftSendResult(BaseModel):
    message_id: str
    body: str
    sent_at: datetime


class HandoffResult(BaseModel):
    conversation_id: str
    handed_off_at: datetime
